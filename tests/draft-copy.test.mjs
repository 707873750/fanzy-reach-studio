const make=(id,extra={})=>({id,copyGroupId:'batch',captionMode:'shared',sharedCaption:'统一原文',caption:'统一原文',independentCaption:'独立备份',status:'draft',title:'标题',boardName:'test',xScheduledAt:'2030-01-01',...extra});
const a=make('instagram'), b=make('pinterest'), x=make('x',{captionMode:'independent',caption:'X 专属'});
const completed=make('done',{status:'published'}), uncertain=make('unsure',{browserPublish:{state:'uncertain'}}), other=make('other',{copyGroupId:'another'});
let drafts=[a,b,x,completed,uncertain,other];
applyCaptionPatch(drafts,a,{caption:'新统一文案'},'1');
assert.equal(b.caption,'新统一文案');assert.equal(x.caption,'X 专属');assert.equal(x.sharedCaption,'新统一文案');
assert.equal(completed.caption,'统一原文');assert.equal(uncertain.caption,'统一原文');assert.equal(other.caption,'统一原文');
assert.equal(b.boardName,'test');assert.equal(b.title,'标题');assert.equal(b.xScheduledAt,'2030-01-01');
applyCaptionPatch(drafts,x,{captionMode:'shared',caption:'不应覆盖'},'2');
assert.equal(x.caption,'新统一文案');assert.equal(x.independentCaption,'X 专属');
applyCaptionPatch(drafts,x,{captionMode:'independent'},'3');assert.equal(x.caption,'X 专属');
applyCaptionPatch(drafts,x,{caption:''},'4');assert.equal(x.caption,'');
applyCaptionPatch(drafts,x,{captionMode:'shared'},'5');
applyCaptionPatch(drafts,x,{captionMode:'independent'},'6');assert.equal(x.caption,'');
// Persistence round-trip, including independent drafts receiving shared version updates.
drafts=JSON.parse(JSON.stringify(drafts));
applyCaptionPatch(drafts,drafts[2],{captionMode:'shared'},'7');assert.equal(drafts[2].caption,'新统一文案');
const legacy=make('legacy',{copyGroupId:undefined,captionMode:undefined,caption:'旧草稿'});
applyCaptionPatch([legacy],legacy,{caption:'仍可编辑'},'8');assert.equal(legacy.caption,'仍可编辑');
assert.throws(()=>applyCaptionPatch([legacy],legacy,{captionMode:'shared'},'9'),/关联批次/);
for(const state of ['running','uncertain','scheduled','succeeded']) assert.equal(canEditCopy(make(state,{browserPublish:{state}})),false);
console.log('PASS: shared/independent captions, mode round-trips, persistence, legacy drafts and protected results');

